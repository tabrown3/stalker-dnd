// Runs the whole pipeline on a CSV export: read, convert, validate.
import { convert } from "./convert.ts";
import type { Issue } from "./issues.ts";
import type { Dataset } from "./schema.ts";
import { findBlock, hasColumn, readGrid } from "./sheet.ts";
import { validate } from "./validate.ts";

export const SOURCE_CSV = "data/source/stalker-dnd-sheet.csv";

export function runPipeline(csvPath: string = SOURCE_CSV): { data?: Dataset; issues: Issue[] } {
  const grid = readGrid(csvPath);
  const { data, issues } = convert(grid);
  if (!data) return { issues };
  const hasFireModeColumn = hasColumn(findBlock(grid, ["Name", "Ammo Type"]), "Fire");
  return { data, issues: [...issues, ...validate(data, { hasFireModeColumn })] };
}

/** The generated files: path -> contents. */
export function outputFiles(data: Dataset, issues: Issue[]): Record<string, string> {
  const json = (v: unknown) => JSON.stringify(v, null, 2) + "\n";
  return {
    "data/weapons.json": json(data.weapons),
    "data/ammo.json": json({ calibers: data.ammo, variants: data.ammoVariants }),
    "data/armor.json": json(data.armor),
    "data/factions.json": json(data.factions),
    "data/tables.json": json(data.tables),
    "data/validation-report.md": report(issues),
  };
}

export function report(issues: Issue[]): string {
  const lines = [
    "# Sheet validation report",
    "",
    `Generated by \`npm run data\` from \`${SOURCE_CSV}\`. Warnings point at values that look wrong;`,
    "nothing here was changed in the data. Info items are expected quirks the converter handled.",
    "",
  ];
  for (const sev of ["error", "warning", "info"] as const) {
    const items = issues.filter((i) => i.severity === sev);
    if (items.length === 0) continue;
    lines.push(`## ${sev === "info" ? "Info" : sev[0]!.toUpperCase() + sev.slice(1) + "s"} (${items.length})`, "");
    for (const i of items) lines.push(`- \`${i.code}\`${i.cell ? ` ${i.cell}` : ""}: ${i.message}`);
    lines.push("");
  }
  return lines.join("\n");
}
